//! Tickets store: singleton serial writer of `tickets-list` (write-path slice).
//!
//! This is sub-slice (b1) of the singleton write-serialization design. The
//! previous scaffold slice stood up the crate + build wiring + the state-load
//! path only. This slice gives the actor its **write path**: it becomes a
//! message-server receiver that applies create / set-status / add-comment to its
//! in-module `tickets` list and persists each change back to the `tickets-list`
//! store label.
//!
//! On `actor.init` it loads the existing `tickets-list` store label into
//! in-module state (the same read path the handler's `load_tickets` uses:
//! get-by-label → get → `serde_json::from_str` → `Vec<Ticket>`, empty Vec if
//! unset), logs the count, keeps the vec in module state (surfaced by
//! `actor.get-state`), and `register()`s with the message router so routed
//! requests get delivered to `handle-request`.
//!
//! As of the (b2) cutover slice the handler routes all writes here via
//! `message-server-host.request`, so this actor is the live serial writer (no
//! longer dormant). The mutation logic is ported faithfully from
//! `ticket-handler`'s `handle_create` / `handle_set_status` / `handle_add_comment`
//! (minus the HTTP + email-notification shells). The cutover adds one thing to
//! the wire contract: `set_status` now also returns `prev_status` so the handler
//! can render an accurate status-change notification without a pre-read.

