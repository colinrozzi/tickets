//! Tickets store: singleton serial writer of `tickets-list` (scaffold slice).
//!
//! This is sub-slice (a) of the singleton write-serialization design. It stands
//! up the crate + build wiring + the state-load path ONLY — it is an inert,
//! buildable skeleton: no HTTP, no messaging, no writes.
//!
//! On `actor.init` it loads the existing `tickets-list` store label into
//! in-module state (the same read path the handler's `load_tickets` uses:
//! get-by-label → get → `serde_json::from_str` → `Vec<Ticket>`, empty Vec if
//! unset), logs the count, and keeps the vec in module state so
//! `actor.get-state` can surface it.
//!
//! A later cutover slice adds the message handlers + moves the write logic in.
//! Deliberately messaging-free so it builds on the well-trodden store+self
//! import surface.

#![no_std]
extern crate alloc;

use alloc::boxed::Box;
use alloc::format;
use alloc::string::String;
use alloc::vec;
use alloc::vec::Vec;
use packr_guest::{export, import, pack_types, GraphValue, Value, ValueType};
use serde::{Deserialize, Serialize};
use theater_guest::State;

packr_guest::setup_guest!();

pack_types! {
    imports {
        theater:simple/self {
            log: func(msg: string),
        }
        theater:simple/store {
            get: func(store-id: string, content-ref: string) -> result<list<u8>, string>,
            get-by-label: func(store-id: string, label: string) -> result<option<string>, string>,
        }
    }
    exports {
        theater:simple/actor.init: func(config: value) -> result<_, string>,
        // Auto-generated by #[derive(State)]; declared so has_export finds it.
        theater:simple/actor.get-state: func() -> value,
    }
}

#[import(module = "theater:simple/self", name = "log")]
fn log(msg: String);

#[import(module = "theater:simple/store", name = "get")]
fn store_get(store_id: String, content_ref: String) -> Result<Vec<u8>, String>;

#[import(module = "theater:simple/store", name = "get-by-label")]
fn store_get_by_label(store_id: String, label: String) -> Result<Option<String>, String>;

const STORE_ID: &str = "tickets";
const TICKETS_LIST_LABEL: &str = "tickets-list";

// ============================================================================
// Data types
// ============================================================================

/// Mirror of `ticket-handler`'s `Ticket` so the stored `tickets-list` JSON
/// deserializes byte-for-byte. The serde field set + `#[serde(default)]` markers
/// (`project` / `updated_at` / `comments`) are identical. The one addition is
/// `#[derive(GraphValue)]`: this actor holds the vec in in-module state, so the
/// `State` derive needs each element convertible to a graph `Value` (the handler
/// keeps empty state and so doesn't). serde attributes are ignored by GraphValue.
#[derive(Serialize, Deserialize, Clone, GraphValue)]
struct Ticket {
    id: u64,
    title: String,
    body: String,
    reporter: String,
    assignee: String,
    status: String,
    #[serde(default)]
    project: String,
    created_at: u64,
    #[serde(default)]
    updated_at: u64,
    #[serde(default)]
    comments: Vec<Comment>,
}

#[derive(Serialize, Deserialize, Clone, GraphValue)]
struct Comment {
    author: String,
    body: String,
    created_at: u64,
}

/// In-module state: the loaded ticket list. Seeded in `init`, surfaced by the
/// `#[derive(State)]`-generated `theater:simple/actor.get-state` export so the
/// actor stays inspectable. The later cutover slice makes this the authoritative
/// serial copy mutated by the write handlers.
#[derive(Clone, GraphValue, State)]
pub struct StoreState {
    pub tickets: Vec<Ticket>,
}

// ============================================================================
// Actor entry points
// ============================================================================

/// `result<_, string>::ok(())`.
fn ok_unit() -> Value {
    let unit = Value::Tuple(vec![]);
    Value::Result {
        ok_type: unit.infer_type(),
        err_type: ValueType::String,
        value: Ok(Box::new(unit)),
    }
}

#[export(name = "theater:simple/actor.init")]
fn init(_config: Value) -> Value {
    let tickets = load_tickets();
    log(format!(
        "[tickets-store] init: loaded {} ticket(s) from {}",
        tickets.len(),
        TICKETS_LIST_LABEL
    ));
    StoreState::set(StoreState { tickets });
    ok_unit()
}

// ============================================================================
// Storage (read path — same as the handler's load_tickets / load_label_as_string)
// ============================================================================

fn load_tickets() -> Vec<Ticket> {
    match load_label_as_string(TICKETS_LIST_LABEL) {
        Ok(json) => serde_json::from_str(&json).unwrap_or_default(),
        Err(_) => Vec::new(),
    }
}

fn load_label_as_string(label: &str) -> Result<String, String> {
    let content_ref = store_get_by_label(String::from(STORE_ID), String::from(label))
        .map_err(|e| format!("{} lookup failed: {}", label, e))?
        .ok_or_else(|| format!("{} not set", label))?;
    let bytes = store_get(String::from(STORE_ID), content_ref)
        .map_err(|e| format!("{} get failed: {}", label, e))?;
    String::from_utf8(bytes).map_err(|_| format!("{} is not valid UTF-8", label))
}
