const STORE_ID: &str = "tickets";
const TICKETS_LIST_LABEL: &str = "tickets-list";

// ============================================================================
// Data types
// ============================================================================

/// Mirror of `ticket-handler`'s `Ticket` so the stored `tickets-list` JSON
/// deserializes byte-for-byte. The serde field set + `#[serde(default)]` markers
/// (`project` / `updated_at` / `comments`) are identical. The one addition is
/// `#[derive(GraphValue)]`: this actor holds the vec in in-module state, so the
/// `State` derive needs each element convertible to a graph `Value` (the handler
/// keeps empty state and so doesn't). serde attributes are ignored by GraphValue.
#[derive(Serialize, Deserialize, Clone, GraphValue)]
struct Ticket {
    id: u64,
    title: String,
    body: String,
    reporter: String,
    assignee: String,
    status: String,
    #[serde(default)]
    project: String,
    created_at: u64,
    #[serde(default)]
    updated_at: u64,
    #[serde(default)]
    comments: Vec<Comment>,
}

#[derive(Serialize, Deserialize, Clone, GraphValue)]
struct Comment {
    author: String,
    body: String,
    created_at: u64,
}

/// The routed write request, tagged by `op`. Decoded from the `message` bytes of
/// a `message-server-client.handle-request` call. Field sets mirror the
/// handler's `NewTicketRequest` / `SetStatusRequest` / `NewCommentRequest`.
/// Status-value validation is NOT done here: the handler validates before
/// sending, so the status is applied verbatim (same for the create/comment
/// required-field checks).
#[derive(Deserialize)]
#[serde(tag = "op")]
enum WriteRequest {
    #[serde(rename = "create")]
    Create {
        title: String,
        body: String,
        reporter: String,
        assignee: String,
        #[serde(default)]
        project: String,
    },
    #[serde(rename = "set_status")]
    SetStatus { id: u64, status: String },
    #[serde(rename = "add_comment")]
    AddComment {
        id: u64,
        author: String,
        body: String,
    },
}

/// Success envelope for create / add_comment: `{"ok":true,"ticket":{<the ticket>}}`.
#[derive(Serialize)]
struct OkResponse<'a> {
    ok: bool,
    ticket: &'a Ticket,
}

/// Success envelope for set_status: as `OkResponse` plus the status the ticket
/// held *before* this call (`prev_status`). The handler needs it to render an
/// accurate `old -> new` status-change notification without re-reading the
/// store. For a no-op (requested status == current) `prev_status` equals the
/// ticket's current status.
#[derive(Serialize)]
struct OkStatusResponse<'a> {
    ok: bool,
    ticket: &'a Ticket,
    prev_status: &'a str,
}

/// Failure envelope: `{"ok":false,"error":"not_found"|"bad_request"}`.
#[derive(Serialize)]
struct ErrResponse<'a> {
    ok: bool,
    error: &'a str,
}

/// In-module state: the loaded ticket list. Seeded in `init`, surfaced by the
/// `#[derive(State)]`-generated `theater:simple/actor.get-state` export so the
/// actor stays inspectable. The later cutover slice makes this the authoritative
/// serial copy mutated by the write handlers.
#[derive(Clone, GraphValue, State)]
pub struct StoreState {
    pub tickets: Vec<Ticket>,
}

// ============================================================================
// Actor entry points
// ============================================================================

/// `result<_, string>::ok(())`.
fn ok_unit() -> Value {
    let unit = Value::Tuple(vec![]);
    Value::Result {
        ok_type: unit.infer_type(),
        err_type: ValueType::String,
        value: Ok(Box::new(unit)),
    }
}

/// `result<T, string>::ok(value)`.
fn ok_result(value: Value) -> Value {
    Value::Result {
        ok_type: value.infer_type(),
        err_type: ValueType::String,
        value: Ok(Box::new(value)),
    }
}

fn bytes_to_list(bytes: Vec<u8>) -> Value {
    Value::List {
        elem_type: ValueType::U8,
        items: bytes.into_iter().map(Value::U8).collect(),
    }
}

#[export(name = "theater:simple/actor.init")]
fn init(_config: Value) -> Value {
    let tickets = load_tickets();
    log(format!(
        "[tickets-store] init: loaded {} ticket(s) from {}",
        tickets.len(),
        TICKETS_LIST_LABEL
    ));
    StoreState::set(StoreState { tickets });
    // Join the message router so routed write requests get delivered to
    // `handle-request`. Best-effort: log on failure, but don't fail init.
    if let Err(e) = register() {
        log(format!("[tickets-store] register failed: {}", e));
    }
    ok_unit()
}

// ============================================================================
// Write path — message-server receiver.
//
// Mutates the in-module `tickets` Vec (the authoritative serial copy) and
// persists the whole Vec back to the `tickets-list` label after each change.
// Logic ported from `ticket-handler`'s handle_create / handle_set_status /
// handle_add_comment, operating on `StoreState::with_mut` instead of a
// per-request `load_tickets` + `save_tickets` round-trip.
// ============================================================================

/// Decode `message` as a JSON write request, dispatch, and return JSON response
/// bytes. On success `{"ok":true,"ticket":{..}}`; unknown id → `not_found`;
/// malformed request → `bad_request`.
#[export(name = "theater:simple/message-server-client.handle-request")]
fn handle_request(_request_id: String, message: Vec<u8>) -> Value {
    let response = dispatch(&message);
    let response_option = Value::Option {
        inner_type: ValueType::List(Box::new(ValueType::U8)),
        value: Some(Box::new(bytes_to_list(response))),
    };
    ok_result(response_option)
}

fn dispatch(message: &[u8]) -> Vec<u8> {
    let text = match core::str::from_utf8(message) {
        Ok(s) => s,
        Err(_) => return error_response("bad_request"),
    };
    let req: WriteRequest = match serde_json::from_str(text) {
        Ok(r) => r,
        Err(_) => return error_response("bad_request"),
    };
    match req {
        WriteRequest::Create {
            title,
            body,
            reporter,
            assignee,
            project,
        } => handle_create(title, body, reporter, assignee, project),
        WriteRequest::SetStatus { id, status } => handle_set_status(id, status),
        WriteRequest::AddComment { id, author, body } => handle_add_comment(id, author, body),
    }
}

/// create: `id = max(existing)+1`, `status = "open"`, one `timer_now()` read so
/// `created_at == updated_at`; push; persist; return the new ticket.
fn handle_create(
    title: String,
    body: String,
    reporter: String,
    assignee: String,
    project: String,
) -> Vec<u8> {
    let now = timer_now();
    let new = StoreState::with_mut(|s| {
        let next_id = s.tickets.iter().map(|t| t.id).max().unwrap_or(0) + 1;
        let new = Ticket {
            id: next_id,
            title,
            body,
            reporter,
            assignee,
            status: String::from("open"),
            project,
            created_at: now,
            updated_at: now,
            comments: Vec::new(),
        };
        s.tickets.push(new.clone());
        persist(&s.tickets);
        new
    });
    success_response(&new)
}

/// set_status: find by id (→ not_found); no-op guard (current == requested →
/// return unchanged WITHOUT persisting, the #31 behavior); else set status, bump
/// `updated_at`, persist, return updated.
fn handle_set_status(id: u64, status: String) -> Vec<u8> {
    let updated = StoreState::with_mut(|s| {
        let idx = s.tickets.iter().position(|t| t.id == id)?;
        let prev_status = s.tickets[idx].status.clone();
        // Idempotent no-op: setting the status a ticket already holds persists
        // nothing — return the unchanged ticket (prev_status == current).
        if s.tickets[idx].status == status {
            return Some((s.tickets[idx].clone(), prev_status));
        }
        s.tickets[idx].status = status;
        s.tickets[idx].updated_at = timer_now();
        let updated = s.tickets[idx].clone();
        persist(&s.tickets);
        Some((updated, prev_status))
    });
    match updated {
        Some((t, prev_status)) => status_success_response(&t, &prev_status),
        None => error_response("not_found"),
    }
}

/// add_comment: find by id (→ not_found); push comment (`created_at = timer_now()`),
/// bump `updated_at`, persist, return updated.
fn handle_add_comment(id: u64, author: String, body: String) -> Vec<u8> {
    let updated = StoreState::with_mut(|s| {
        let idx = s.tickets.iter().position(|t| t.id == id)?;
        let comment = Comment {
            author,
            body,
            created_at: timer_now(),
        };
        s.tickets[idx].comments.push(comment);
        s.tickets[idx].updated_at = timer_now();
        let updated = s.tickets[idx].clone();
        persist(&s.tickets);
        Some(updated)
    });
    match updated {
        Some(t) => success_response(&t),
        None => error_response("not_found"),
    }
}

fn success_response(ticket: &Ticket) -> Vec<u8> {
    serde_json::to_vec(&OkResponse { ok: true, ticket }).unwrap_or_default()
}

fn status_success_response(ticket: &Ticket, prev_status: &str) -> Vec<u8> {
    serde_json::to_vec(&OkStatusResponse {
        ok: true,
        ticket,
        prev_status,
    })
    .unwrap_or_default()
}

fn error_response(error: &str) -> Vec<u8> {
    serde_json::to_vec(&ErrResponse { ok: false, error }).unwrap_or_default()
}

// ============================================================================
// Storage (read path — same as the handler's load_tickets / load_label_as_string)
// ============================================================================

fn load_tickets() -> Vec<Ticket> {
    match load_label_as_string(TICKETS_LIST_LABEL) {
        Ok(json) => serde_json::from_str(&json).unwrap_or_default(),
        Err(_) => Vec::new(),
    }
}

/// Persist the whole ticket Vec as JSON to the `tickets-list` label — the same
/// serialization the handler's `save_tickets` uses. Best-effort: a store error
/// is swallowed (mirrors the handler), the in-module copy stays authoritative.
fn persist(tickets: &[Ticket]) {
    let json = serde_json::to_vec(tickets).unwrap_or_default();
    let _ = store_store_at_label(
        String::from(STORE_ID),
        String::from(TICKETS_LIST_LABEL),
        json,
    );
}

fn load_label_as_string(label: &str) -> Result<String, String> {
    let content_ref = store_get_by_label(String::from(STORE_ID), String::from(label))
        .map_err(|e| format!("{} lookup failed: {}", label, e))?
        .ok_or_else(|| format!("{} not set", label))?;
    let bytes = store_get(String::from(STORE_ID), content_ref)
        .map_err(|e| format!("{} get failed: {}", label, e))?;
    String::from_utf8(bytes).map_err(|_| format!("{} is not valid UTF-8", label))
}
