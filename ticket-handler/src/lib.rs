#[derive(Serialize, Deserialize, Clone)]
struct Ticket {
    id: u64,
    title: String,
    body: String,
    reporter: String,
    assignee: String,
    status: String,
    /// Project this ticket belongs to (e.g. "inbox", "tickets"). Lets the flat
    /// list be scoped by `?project=`. Older stored tickets won't have this field
    /// — `default` makes them deserialize as `""` (same back-compat trick as
    /// `comments` / `updated_at`). Always serialized (no `skip_serializing_if`).
    #[serde(default)]
    project: String,
    created_at: u64,
    /// Last-activity timestamp: set equal to `created_at` on create, then
    /// bumped to `timer_now()` on every subsequent change (status transition,
    /// new comment). Older stored tickets won't have this field — `default`
    /// makes them deserialize as `0` (same back-compat trick as `comments`).
    #[serde(default)]
    updated_at: u64,
    /// Append-only comment thread. Older stored tickets (pre phase-2 part-2)
    /// won't have this field — `default` makes them deserialize as empty.
    #[serde(default)]
    comments: Vec<Comment>,
}

#[derive(Serialize, Deserialize, Clone)]
struct Comment {
    author: String,
    body: String,
    created_at: u64,
}

#[derive(Deserialize)]
struct NewTicketRequest {
    title: String,
    body: String,
    reporter: String,
    assignee: String,
    /// Optional project scope. Omitted / empty → `""` (back-compat with
    /// existing create requests that predate the project dimension).
    #[serde(default)]
    project: String,
}

#[derive(Deserialize)]
struct SetStatusRequest {
    status: String,
}

#[derive(Deserialize)]
struct NewCommentRequest {
    author: String,
    body: String,
}

#[derive(Serialize)]
struct TicketsList {
    tickets: Vec<Ticket>,
}

#[derive(Serialize)]
