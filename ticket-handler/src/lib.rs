//! Tickets handler: per-connection HTTP handler.
//!
//! Receives one HTTP request, routes it, reads/writes ticket state from the
//! shared store, returns JSON, closes the connection, and shuts itself down.
//!
//! Routes:
//!   GET  /healthz                                       → liveness probe (unauthenticated)
//!   GET  /v1/tickets                                    → list (optional ?status=, ?assignee=, ?reporter=, ?project=)
//!   POST /v1/tickets                                    → create
//!   GET  /v1/tickets/<id>                               → show one
//!   POST /v1/tickets/<id>/status                        → set status
//!   POST /v1/tickets/<id>/comment                       → append a comment
//!
//! On create / status-change / new-comment the handler also fires a
//! best-effort notification email to the relevant ticket participants via
//! the inbox HTTP API (TLS POST to /v1/mailboxes/tickets@colinrozzi.com/send,
//! routed from tickets@ to each participant).

