fn handle_list(query: &str) -> Vec<u8> {
    let (status_filter, assignee_filter, reporter_filter, project_filter) = parse_query(query);
    let all = load_tickets();
    let filtered: Vec<Ticket> = all
        .into_iter()
        .filter(|t| match &status_filter {
            Some(s) => &t.status == s,
            None => true,
        })
        .filter(|t| match &assignee_filter {
            Some(a) => &t.assignee == a,
            None => true,
        })
        .filter(|t| match &reporter_filter {
            Some(r) => &t.reporter == r,
            None => true,
        })
        .filter(|t| match &project_filter {
            Some(p) => &t.project == p,
            None => true,
        })
        .collect();
    let body = serde_json::to_vec(&TicketsList { tickets: filtered }).unwrap_or_default();
    http_response(200, body)
}

fn handle_show(id_str: &str) -> Vec<u8> {
    let id: u64 = match id_str.parse() {
        Ok(n) => n,
        Err(_) => return http_response(400, br#"{"error":"invalid ticket id"}"#.to_vec()),
    };
    let all = load_tickets();
    match all.into_iter().find(|t| t.id == id) {
        Some(t) => {
            let body = serde_json::to_vec(&t).unwrap_or_default();
            http_response(200, body)
        }
        None => http_response(404, br#"{"error":"ticket not found"}"#.to_vec()),
    }
}

fn handle_create(request_str: &str) -> Vec<u8> {
    let body = match request_str.find("\r\n\r\n") {
        Some(i) => &request_str[i + 4..],
        None => return http_response(400, br#"{"error":"missing body"}"#.to_vec()),
    };

    let req: NewTicketRequest = match serde_json::from_str(body) {
        Ok(r) => r,
        Err(e) => {
            let msg = format!(r#"{{"error":"bad request body: {}"}}"#, e);
            return http_response(400, msg.into_bytes());
        }
    };
    if req.title.is_empty() || req.reporter.is_empty() || req.assignee.is_empty() {
        return http_response(
            400,
            br#"{"error":"title, reporter, and assignee are required"}"#.to_vec(),
        );
    }

    let mut all = load_tickets();
    let next_id = all.iter().map(|t| t.id).max().unwrap_or(0) + 1;
    // One `timer_now()` read so a freshly created ticket has
    // `updated_at == created_at` exactly.
    let now = timer_now();
    let new = Ticket {
        id: next_id,
        title: req.title,
        body: req.body,
        reporter: req.reporter,
        assignee: req.assignee,
        status: String::from("open"),
        project: req.project,
        created_at: now,
        updated_at: now,
        comments: Vec::new(),
    };
    all.push(new.clone());
    save_tickets(&all);

    notify_created(&new);

    let body = serde_json::to_vec(&new).unwrap_or_default();
    http_response(201, body)
}

fn handle_set_status(id_str: &str, request_str: &str) -> Vec<u8> {
    let id: u64 = match id_str.parse() {
        Ok(n) => n,
        Err(_) => return http_response(400, br#"{"error":"invalid ticket id"}"#.to_vec()),
    };

    let body = match request_str.find("\r\n\r\n") {
        Some(i) => &request_str[i + 4..],
        None => return http_response(400, br#"{"error":"missing body"}"#.to_vec()),
    };

    let req: SetStatusRequest = match serde_json::from_str(body) {
        Ok(r) => r,
        Err(e) => {
            let msg = format!(r#"{{"error":"bad request body: {}"}}"#, e);
            return http_response(400, msg.into_bytes());
        }
    };

    if !VALID_STATUSES.iter().any(|s| *s == req.status) {
        let msg = format!(
            r#"{{"error":"invalid status {:?}; valid values: open, in-progress, done, closed"}}"#,
            req.status
        );
        return http_response(400, msg.into_bytes());
    }

    let mut all = load_tickets();
    let idx = match all.iter().position(|t| t.id == id) {
        Some(i) => i,
        None => return http_response(404, br#"{"error":"ticket not found"}"#.to_vec()),
    };
    // Idempotent no-op: setting a ticket to the status it already holds is a
    // true no-op. Transitions are any-to-any, so this is a legitimate request
    // (and even exercised by tests/status.sh's done -> done case) — return 200
    // with the unchanged ticket, but skip the store rewrite and the
    // notification emails. Only a genuine transition persists + notifies.
    if all[idx].status == req.status {
        let body = serde_json::to_vec(&all[idx]).unwrap_or_default();
        return http_response(200, body);
    }

    let old_status = all[idx].status.clone();
    all[idx].status = req.status;
    all[idx].updated_at = timer_now();
    let updated = all[idx].clone();
    save_tickets(&all);

    notify_status_changed(&updated, &old_status);

    let body = serde_json::to_vec(&updated).unwrap_or_default();
    http_response(200, body)
}

fn handle_add_comment(id_str: &str, request_str: &str) -> Vec<u8> {
    let id: u64 = match id_str.parse() {
        Ok(n) => n,
        Err(_) => return http_response(400, br#"{"error":"invalid ticket id"}"#.to_vec()),
    };

    let body = match request_str.find("\r\n\r\n") {
        Some(i) => &request_str[i + 4..],
        None => return http_response(400, br#"{"error":"missing body"}"#.to_vec()),
    };

    let req: NewCommentRequest = match serde_json::from_str(body) {
        Ok(r) => r,
        Err(e) => {
            let msg = format!(r#"{{"error":"bad request body: {}"}}"#, e);
            return http_response(400, msg.into_bytes());
        }
    };
    if req.author.is_empty() || req.body.is_empty() {
        return http_response(400, br#"{"error":"author and body are required"}"#.to_vec());
    }

    let mut all = load_tickets();
    let idx = match all.iter().position(|t| t.id == id) {
        Some(i) => i,
        None => return http_response(404, br#"{"error":"ticket not found"}"#.to_vec()),
    };
    let comment = Comment {
        author: req.author,
        body: req.body,
        created_at: timer_now(),
    };
    all[idx].comments.push(comment.clone());
    all[idx].updated_at = timer_now();
    let updated = all[idx].clone();
    save_tickets(&all);

    notify_comment_added(&updated, &comment);

    let body = serde_json::to_vec(&updated).unwrap_or_default();
    http_response(201, body)
}

